#!/usr/bin/env bash
#
# route.sh —— 把 task-probe 的执行结果转换成约定的业务结果
#
# 用法: route.sh MODE ITEM
#   MODE ∈ {ok, retry, fatal}
#   ITEM ∈ 1~32 个英文字母或数字
#
# 由调用环境提供(不写死,评测会换):
#   TASK_TOOL_DIR  存放 task-probe 的目录
#   ROUTE_RESULT   结果文件的输出路径
# 由配置文件提供:
#   job.env(与脚本同目录,找不到则退回 /workspace/job.env) → ACCESS_TOKEN

# ---------------------------------------------------------------------------
# 0. 注意:这里【故意不写】set -e
#    task-probe 的 11 / 23 是正常业务状态,不是错误。
#    若开了 set -e,脚本会在返回 11 的那一行直接中断,
#    我们根本没机会把 11 翻译成 75、把 23 翻译成 65。
# ---------------------------------------------------------------------------

# ---------------------------------------------------------------------------
# 1. 参数校验:不合法就打印 usage、退出 64,并且【不生成结果文件】
# ---------------------------------------------------------------------------
usage() {
    printf 'usage: route.sh MODE ITEM  (MODE: ok|retry|fatal, ITEM: 1-32 alnum)\n'
}

if [ "$#" -ne 2 ]; then
    usage
    exit 64
fi

mode=$1
item=$2

# MODE 只能是 ok / retry / fatal
case "$mode" in
    ok|retry|fatal) ;;
    *) usage; exit 64 ;;
esac

# ITEM 必须非空、且只含英文字母或数字
case "$item" in
    ''|*[!A-Za-z0-9]*) usage; exit 64 ;;
esac

# ITEM 长度不得超过 32
if [ "${#item}" -gt 32 ]; then
    usage
    exit 64
fi

# ---------------------------------------------------------------------------
# 2. 读配置,并【导出】ACCESS_TOKEN
#    提示1:父 shell 里赋的值默认对子进程不可见,必须 export。
#    用 set -a(allexport)包住 source,配置里赋的变量就自动导出。
# ---------------------------------------------------------------------------
config="$(dirname "$(readlink -f "$0")")/job.env"
[ -f "$config" ] || config="/workspace/job.env"

set -a
. "$config"
set +a

# ---------------------------------------------------------------------------
# 3. 让 task-probe 能【按命令名】被找到
#    提示2:按名字调用依赖 PATH;把工具目录放到最前,但必须【保留原来的 $PATH】,
#    否则 ls、printf 这些系统命令也一起失灵了。
# ---------------------------------------------------------------------------
PATH="${TASK_TOOL_DIR}:${PATH}"
export PATH

# ---------------------------------------------------------------------------
# 4. 调用工具,并【立刻】保存退出码
#    提示3:任何一条命令都会刷新 $?,所以 status=$? 必须紧贴工具调用,
#    中间不能插别的命令(连 echo 都不行)。
# ---------------------------------------------------------------------------
output=$(task-probe "$mode" "$item")
status=$?

# ---------------------------------------------------------------------------
# 5. 把工具的退出码翻译成业务结果
# ---------------------------------------------------------------------------
case "$status" in
    0)
        # 成功:结果原样使用工具打印的 receipt:<值>
        result=$output
        rc=0
        ;;
    11)
        result="retry:$item"
        rc=75
        ;;
    23)
        result="rejected:$item"
        rc=65
        ;;
    *)
        # 未定义的退出码(如 31 密钥错误、127 命令找不到):
        # 不写结果文件,原样返回退出码,方便排查。
        exit "$status"
        ;;
esac

# ---------------------------------------------------------------------------
# 6. 写结果文件
#    printf 会【覆盖】旧内容,并保证恰好一个结尾换行。
#    不用 echo:printf 对格式更可控。
# ---------------------------------------------------------------------------
printf '%s\n' "$result" > "$ROUTE_RESULT"

exit "$rc"
